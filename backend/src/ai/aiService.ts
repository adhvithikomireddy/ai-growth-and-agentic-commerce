import { GoogleGenerativeAI } from "@google/generative-ai";
import { env } from "../config/env.js";
import { logger } from "../utils/logger.js";
import { IProduct } from "../models/Product.js";

let genAI: GoogleGenerativeAI | null = null;

if (env.GEMINI_API_KEY) {
  try {
    genAI = new GoogleGenerativeAI(env.GEMINI_API_KEY);
    logger.info("Gemini AI client initialized successfully.");
  } catch (error: any) {
    logger.warn("Failed to initialize Gemini AI SDK, using fallback engine:", error.message);
  }
}

export interface RecommendationResponse {
  summary: string;
  recommendations: Array<{
    productId: string;
    reason: string;
  }>;
  suggestedAction?: string;
  crossSellSuggestion?: string;
}

export const generateAgentExplanation = async (
  query: string,
  products: IProduct[],
  language: "en" | "hi" | "te" = "en",
  context?: { budgetMax?: number; requirements?: string[]; intent?: string }
): Promise<RecommendationResponse> => {
  // If Gemini API is available, invoke it with strict bounds
  if (genAI) {
    try {
      const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });
      const prompt = `
You are a professional, helpful Commerce Buyer Agent representing an Indian customer.
The customer asked: "${query}"
Language selected: ${language} (en = English, hi = Hindi, te = Telugu).
Customer constraints: Budget <= ?${context?.budgetMax || "unspecified"}, requirements: ${context?.requirements?.join(", ") || "general"}.

Authoritative Products Found from Merchant Catalog:
${products.map(p => `- ID: ${p.productId}, Name: ${p.name}, Price: ?${p.price}, Specs: ${JSON.stringify(p.specifications || {})}`).join("\n")}

Instructions:
1. Formulate a brief, helpful 1-2 sentence conversational summary in the requested language (${language}).
2. Provide a 1-sentence recommendation reason for each product explaining why it fits their requirement.
3. DO NOT invent new products, prices, or fake discounts.
4. Output STRICT JSON format only:
{
  "summary": "...",
  "recommendations": [
    { "productId": "...", "reason": "..." }
  ],
  "crossSellSuggestion": "..."
}
`;
      const result = await model.generateContent(prompt);
      const text = result.response.text();
      const cleanJson = text.replace(/```json/g, "").replace(/```/g, "").trim();
      const parsed = JSON.parse(cleanJson);
      return parsed;
    } catch (err: any) {
      logger.warn("Gemini API call failed, falling back to deterministic explanation engine:", err.message);
    }
  }

  // High-precision Deterministic Multilingual Fallback Engine
  return generateDeterministicExplanation(query, products, language, context);
};

